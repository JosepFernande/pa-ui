#!/usr/bin/env node
/**
 * Residual-identifier guard (issue #139, S4 task 4.10).
 *
 * Scans every git-tracked file for stray `pa-ui`/`--pa-`/`PA_`/`.pa-`
 * brand-identity strings that should have been renamed to `halo-ui`/
 * `--ha-`/`HA_`/`.ha-` during the rebrand, and fails loudly if any survive
 * outside the documented exceptions below.
 *
 * **Deviation from the tasks doc's literal regex** (documented here on
 * purpose, not silently narrowed): the originally proposed check used a
 * blanket `\bpa-ui\b` bare-word match. Running that against the real repo
 * produced ~150 false positives, because the design ALSO explicitly decided
 * to keep referring to the GitHub repo and product by the name "pa-ui" in
 * prose everywhere (skill frontmatter `project: pa-ui`, "the pa-ui
 * repository", README/CONTRIBUTING/AGENTS.md prose, decision-doc slugs like
 * `pa-ui-default-theme-design-values`). A blanket bare-word check is
 * fundamentally incompatible with that decision. This script instead
 * targets the ACTUAL residual-identifier risk — stale COMPOUND identifiers
 * that should have migrated (`pa-ui-rules`, `pa-ui-architecture`,
 * `libs/pa-ui`, etc.) — via `STALE_COMPOUND_RE`, and leaves bare "pa-ui"
 * prose alone. `@pa-ui`, `--pa-`, `\bPA_`, and `\.pa-` are still checked
 * blanket, exactly as specified, since those have no legitimate prose use.
 *
 * Two kinds of exception:
 *
 *  1. File-level allowlist — files that MUST legitimately still contain
 *     `--pa-*`: the legacy CSS-alias implementation/spec/artifact, every
 *     spec file that asserts the alias contract end-to-end (theme service/
 *     provider + the 3 libs' theme-runtime integration specs), the
 *     migration doc itself (which documents the old names by design), and
 *     already-released package CHANGELOGs (historical record — a released
 *     changelog entry is immutable once shipped).
 *
 *  2. Line-level exceptions — individual matches that are legitimate no
 *     matter which file they're in, because the design explicitly decided
 *     NOT to rename them:
 *       - `JosepFernande/pa-ui` — the GitHub repo itself is NOT renamed.
 *       - `pa-ui.wiki` — the GitHub Wiki repo, same reason.
 *       - `decision/pa-ui-*`, `audit/pa-ui-*`, `pa-ui-default-theme-*` —
 *         historical Notion/decision-log identifiers. These are immutable
 *         external references, not brand identity, and renaming the slug
 *         would break traceability to the actual decision record.
 *
 * Usage: node tools/release/check-residual.mjs
 */
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = fileURLToPath(new URL('.', import.meta.url));
const repoRoot = resolve(scriptDir, '../..');

const FILE_ALLOWLIST_EXACT = new Set([
  'libs/core/src/lib/foundation/legacy-token-alias.ts',
  'libs/core/src/lib/foundation/legacy-token-alias.spec.ts',
  'libs/core/src/lib/foundation/theme.css',
  'libs/core/src/lib/theme/theme.service.spec.ts',
  'libs/core/src/lib/theme/theme-provider.spec.ts',
  'libs/button/src/lib/theme-runtime.integration.spec.ts',
  'libs/input/src/lib/theme-runtime.integration.spec.ts',
  'libs/select/src/lib/theme-runtime.integration.spec.ts',
  'docs/migration-pa-ui-to-halo-ui.md',
  // Historical-rename narrative, deliberately worded with "formerly"/
  // "pre-#139"/"at the time of #85" qualifiers — same category as the
  // migration doc, not a missed rename.
  'skills/lib-ui-architecture/SKILL.md',
  'skills/lib-ui-release/SKILL.md',
  // Intentionally exercises the OLD `pa-` prefix to prove the stylelint
  // rule rejects it (and accepts it only under the transitional
  // `{prefixes:["ha-","pa-"]}` option) — same category as
  // legacy-token-alias.spec.ts.
  'tools/stylelint/halo-ui-rules/src/rules/__tests__/prefix-selector.test.ts',
]);

/** Matches libs/<any>/CHANGELOG.md — already-released, immutable history. */
const CHANGELOG_RE = /^libs\/[^/]+\/CHANGELOG\.md$/;

/** package-lock.json is generated/regenerated by npm, not hand-audited. */
const FILE_ALLOWLIST_EXTRA = new Set(['package-lock.json']);

const LINE_EXCEPTION_PATTERNS = [
  /JosepFernande\/pa-ui/,
  /pa-ui\.wiki/,
  /decision\/pa-ui-[\w-]+/,
  /audit\/pa-ui-[\w-]+/,
  /pa-ui-default-theme-[\w-]+/,
];

/** `@pa-ui`, `--pa-`, `PA_`, `.pa-` — no legitimate prose use, always residual. */
const STRICT_RE = /@pa-ui|--pa-|\bPA_|\.pa-/;

/**
 * Stale COMPOUND identifiers only — `pa-ui-<something>` or a NESTED `pa-ui`
 * path segment (preceded by an actual `/`, so a directory-tree diagram's
 * root label `pa-ui/` at the start of a line is not a false positive — the
 * repo root itself is legitimately still called `pa-ui`) — never bare
 * prose. See the file-level doc comment above for why.
 */
const STALE_COMPOUND_RE = /\bpa-ui-[\w-]+|\/pa-ui\//;

function isAllowlistedFile(relPath) {
  if (FILE_ALLOWLIST_EXACT.has(relPath)) return true;
  if (FILE_ALLOWLIST_EXTRA.has(relPath)) return true;
  if (CHANGELOG_RE.test(relPath)) return true;
  return false;
}

function lineHasResidual(line) {
  const hasStrict = STRICT_RE.test(line);
  const hasCompound = STALE_COMPOUND_RE.test(line);
  if (!hasStrict && !hasCompound) return false;

  let remaining = line;
  for (const pattern of LINE_EXCEPTION_PATTERNS) {
    remaining = remaining.replace(new RegExp(pattern.source, 'g'), '');
  }
  return STRICT_RE.test(remaining) || STALE_COMPOUND_RE.test(remaining);
}

export function findResidualMatches(relPath, content) {
  if (isAllowlistedFile(relPath)) return [];
  const matches = [];
  const lines = content.split('\n');
  for (let i = 0; i < lines.length; i += 1) {
    const line = lines[i];
    if (lineHasResidual(line)) {
      matches.push({ line: i + 1, text: line.trim() });
    }
  }
  return matches;
}

function trackedFiles() {
  const out = execFileSync('git', ['ls-files'], { cwd: repoRoot, encoding: 'utf8' });
  return out.split('\n').filter(Boolean);
}

const isMainModule = process.argv[1] && import.meta.url === `file://${process.argv[1]}`;

if (isMainModule) {
  console.log('Scanning for residual pa-ui identifiers...');
  const failures = [];
  for (const relPath of trackedFiles()) {
    let content;
    try {
      content = readFileSync(join(repoRoot, relPath), 'utf8');
    } catch {
      continue; // binary file, symlink to nowhere, etc.
    }
    const matches = findResidualMatches(relPath, content);
    for (const m of matches) {
      failures.push(`${relPath}:${m.line}: ${m.text}`);
    }
  }

  if (failures.length > 0) {
    console.error(`\nFound ${failures.length} residual identifier(s):\n`);
    for (const f of failures) console.error(`  - ${f}`);
    console.error(
      '\nRename these to the halo-ui equivalent, or add a documented exception ' +
        'in tools/release/check-residual.mjs if it is genuinely intentional.',
    );
    process.exit(1);
  }
  console.log('Clean — no undocumented residual pa-ui identifiers found.');
}
